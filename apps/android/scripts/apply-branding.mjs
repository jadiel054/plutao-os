import { cp, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(scriptsDir, "..");
const source = path.join(appDir, "branding", "res");
const target = path.join(appDir, "android", "app", "src", "main", "res");
const manifestPath = path.join(appDir, "android", "app", "src", "main", "AndroidManifest.xml");

const nativeSourceDir = path.join(appDir, "native");
const javaTargetDir = path.join(appDir, "android", "app", "src", "main", "java", "app", "plutao", "os");
const mainActivityPath = path.join(javaTargetDir, "MainActivity.java");

await mkdir(target, { recursive: true });
await cp(source, target, { recursive: true, force: true });

// Copy native plugin source files into android/ if regenerated by cap add android
try {
  await mkdir(javaTargetDir, { recursive: true });
  await cp(nativeSourceDir, javaTargetDir, { recursive: true, force: true });

  try {
    let mainActivity = await readFile(mainActivityPath, "utf8");
    if (!mainActivity.includes("LocalModelPlugin.class")) {
      if (mainActivity.includes("public class MainActivity extends BridgeActivity {}")) {
        mainActivity = mainActivity.replace(
          "public class MainActivity extends BridgeActivity {}",
          `public class MainActivity extends BridgeActivity {
    @Override
    public void onCreate(android.os.Bundle savedInstanceState) {
        registerPlugin(LocalModelPlugin.class);
        super.onCreate(savedInstanceState);
    }
}`
        );
        await writeFile(mainActivityPath, mainActivity);
      }
    }
  } catch {
    // MainActivity might not exist yet if cap add android hasn't run locally
  }
} catch {
  // Ignore if nativeSourceDir not found
}

const manifest = await readFile(manifestPath, "utf8");
const oauthIntentFilter = `            <intent-filter>\n                <action android:name="android.intent.action.VIEW" />\n                <category android:name="android.intent.category.DEFAULT" />\n                <category android:name="android.intent.category.BROWSABLE" />\n                <data android:scheme="plutao" android:host="oauth" />\n            </intent-filter>`;
if (!manifest.includes('android:scheme="plutao"')) {
  const updatedManifest = manifest.replace(
    `                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>`,
    `                <category android:name="android.intent.category.LAUNCHER" />\n            </intent-filter>\n${oauthIntentFilter}`
  );
  await writeFile(manifestPath, updatedManifest);
}
console.log(`Applied Plutão Android branding and native plugins from ${source}`);
